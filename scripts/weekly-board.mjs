#!/usr/bin/env node
/**
 * Write this week's board into data/leaderboard.json — once per ISO week, additively.
 *
 *   npm run board            # write the current week if it is not there yet
 *   npm run board -- --force # re-score the current week (replaces only that week)
 *
 * The board is the top 50 entries across every visible shelf, in the archive's editorial
 * order: Jev's usefulness judgment, public popularity breaking ties. It is written down
 * with the date it was scored so the leaderboard's "This week" tab names a measurement,
 * and so next week's board can show what moved. Earlier weeks are never removed.
 *
 * The harvest runs this daily; on six days out of seven it writes nothing.
 */

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';
import { mergeLive } from '../assets/js/archive.js';
import { attachRankings } from '../assets/js/ranking.js';
import { isoWeek, snapshot } from '../assets/js/weekly-board.js';
import { visible } from './build-pages.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'data', 'leaderboard.json');
const read = async f => JSON.parse(await readFile(join(ROOT, 'data', f), 'utf8'));

async function main() {
  const force = process.argv.includes('--force');
  const cfg = await read('index.json');
  const live = await read('live.json').catch(() => ({ github: [] }));
  const rankings = await read('rankings.json').catch(() => null);
  const byRepo = new Map((live.github || []).map(g => [g.repo.toLowerCase(), g]));

  const data = {};
  for (const section of cfg.sections) {
    if (!section.file) continue;
    data[section.id] = (await read(section.file)).items;
  }
  mergeLive(data, live);
  const items = [];
  for (const [shelf, list] of Object.entries(data))
    for (const it of list) if (await visible(it, byRepo)) items.push({ ...it, shelf });
  await attachRankings(items, rankings);

  const week = isoWeek(new Date());
  const board = await read('leaderboard.json').catch(() => ({ weeks: [] }));
  board.note ??= 'GENERATED by scripts/weekly-board.mjs — one scored board per ISO week, top 50 across every shelf, in the editorial order (Jev usefulness, popularity breaks ties). Never hand-edit; earlier weeks are never removed.';
  const existing = board.weeks.findIndex(w => w.week === week);
  if (existing > -1 && !force) {
    console.log(`${week} is already on the board (scored ${board.weeks[existing].scoredAt}); nothing written. Use --force to re-score it.`);
    return;
  }
  const snap = snapshot(items, { week, scoredAt: new Date().toISOString() });
  if (!snap.entries.length) throw new Error('No classified entries to score; nothing written. Run npm run rank first.');
  if (existing > -1) board.weeks[existing] = snap; else board.weeks.push(snap);
  board.weeks.sort((a, b) => a.week.localeCompare(b.week));
  await writeFile(OUT, JSON.stringify(board, null, 2) + '\n');
  console.log(`wrote ${week}: top ${snap.entries.length} of ${snap.of} classified entries (${board.weeks.length} week${board.weeks.length === 1 ? '' : 's'} on the board)`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch(error => { console.error(error.message); process.exit(1); });
}
