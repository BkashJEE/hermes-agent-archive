#!/usr/bin/env node
/**
 * Record when each entry first appeared in the archive.
 *
 *   npm run added          # rebuild data/added.json from git history
 *   npm run added -- --dry # report, write nothing
 *
 * "What is new" could not be answered from the data. The `date` field is the date the
 * thing being described was published — a Reddit post from February keeps February — and
 * 290 entries carry no date at all. Sorting by it tells a reader when somebody wrote
 * something, not when this archive started holding it.
 *
 * Git knows. Every commit that touched data/ is a snapshot of what the archive held at
 * that moment, so the first commit containing an id is the day that entry arrived. This
 * walks that history once and writes the answer down.
 *
 * The output is generated. Never hand-edit it: rerun the script, which is also what keeps
 * it honest, because an id that was removed and later restored gets the date it genuinely
 * came back rather than a remembered one.
 */

import { execFileSync } from 'node:child_process';
import { writeFile, readFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'data', 'added.json');

/* stdio 'pipe' for stderr: asking an old commit for a shelf that did not exist yet is an
   expected miss the caller handles, not something to print 50 times. */
const git = args => execFileSync('git', args,
  { cwd: ROOT, maxBuffer: 256 * 1024 * 1024, stdio: ['ignore', 'pipe', 'ignore'] }).toString();

/** The entry ids a given commit held, across every content shelf it had at the time. */
function idsAt(sha, files) {
  const ids = new Set();
  for (const file of files) {
    let raw;
    try { raw = git(['show', `${sha}:data/${file}`]); } catch { continue; }   // shelf not born yet
    let parsed;
    try { parsed = JSON.parse(raw); } catch { continue; }                     // mid-history malformed
    for (const item of (Array.isArray(parsed) ? parsed : parsed.items ?? [])) {
      if (item?.id) ids.add(item.id);
    }
  }
  return ids;
}

async function main() {
  const dry = process.argv.includes('--dry');

  /* Shelf filenames change over time, so take the union of every name the index has used
     rather than only today's. A shelf that was renamed still holds entries that arrived. */
  const index = JSON.parse(await readFile(join(ROOT, 'data', 'index.json'), 'utf8'));
  const files = new Set(index.sections.filter(s => s.file).map(s => s.file));
  for (const name of git(['log', '--all', '--name-only', '--format=', '--', 'data/']).split('\n')) {
    const match = name.trim().match(/^data\/([a-z0-9-]+\.json)$/);
    if (match && !['live.json', 'rankings.json', 'index.json', 'added.json'].includes(match[1])) files.add(match[1]);
  }

  const commits = git(['log', '--reverse', '--format=%H\t%ad', '--date=short', '--', 'data/'])
    .trim().split('\n').filter(Boolean).map(line => line.split('\t'));

  const added = {};
  let seen = new Set();
  for (const [sha, date] of commits) {
    const ids = idsAt(sha, files);
    if (!ids.size) continue;
    for (const id of ids) if (!seen.has(id)) added[id] = date;
    seen = ids;          // an id absent here and present later is genuinely re-added
  }

  /* Only entries the archive currently holds; a removed one has no card to link to. */
  const current = new Set();
  for (const file of index.sections.filter(s => s.file).map(s => s.file)) {
    const raw = JSON.parse(await readFile(join(ROOT, 'data', file), 'utf8'));
    for (const item of (Array.isArray(raw) ? raw : raw.items)) current.add(item.id);
  }
  for (const id of Object.keys(added)) if (!current.has(id)) delete added[id];

  const byDate = {};
  for (const date of Object.values(added)) byDate[date] = (byDate[date] || 0) + 1;
  const dates = Object.entries(byDate).sort((a, b) => b[0].localeCompare(a[0]));

  console.log(`${commits.length} commits read, ${Object.keys(added).length} current entries dated`);
  console.log('\nmost recent arrivals:');
  for (const [date, n] of dates.slice(0, 8)) console.log(`  ${date}  +${n}`);
  const undated = current.size - Object.keys(added).length;
  if (undated) console.log(`\n${undated} current entries found in no commit — unexpected; investigate before trusting the panel.`);

  if (dry) { console.log('\n--dry: nothing written.'); return; }
  await writeFile(OUT, JSON.stringify({
    generatedAt: new Date().toISOString(),
    note: 'GENERATED by scripts/build-added-dates.mjs — when each entry first appeared in the '
        + 'archive, taken from git history. Never hand-edit: the data/*.json date field is the '
        + 'publication date of the thing described, which is a different question.',
    added
  }, null, 2) + '\n');
  console.log(`\nwrote ${OUT.replace(ROOT + '/', '')}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await main();
